class TestD2LeaseTtlExpiry(unittest.TestCase):
    def test_lease_ttl_vs_walking_speed(self):
        print("\n--- [TEST D2.3] 60-Tick Lease TTL Expiry vs Parcel Dimensions ---")
        # GDD 3.4: "Lease-Based Affordance Reservations: Workbenches, tools, and beds are reserved
        # using a 60-tick Time-to-Live (TTL) lease. If an agent fails to arrive before lease expiry,
        # the resource returns to the public pool."
        # Tick rate: 30 Hz (standard simulation tick) or 10 Hz (psychology tick).
        # Normal walking speed: 1.2 m/s = 12 dm/s.
        speed_dm_per_s = 12.0

        # Parcel sizes from GDD 4.3:
        # Suburban: 128 x 128 dm
        # Urban: 64 x 64 dm
        # Eco-Village: 96 x 96 dm
        biomes = {
            "Suburban Sprawl (128x128 dm)": 128.0,
            "Dense Urban (64x64 dm)": 64.0,
            "Eco-Village (96x96 dm)": 96.0,
        }

        # Case A: 30 Hz tick rate (standard engine physics/sim loop)
        ttl_seconds_30hz = 60 / 30.0 # 2.0 seconds
        max_dist_30hz = speed_dm_per_s * ttl_seconds_30hz # 24.0 dm = 2.4 meters

        # Case B: 10 Hz tick rate (DF Psychology & Agency loop)
        ttl_seconds_10hz = 60 / 10.0 # 6.0 seconds
        max_dist_10hz = speed_dm_per_s * ttl_seconds_10hz # 72.0 dm = 7.2 meters

        print(f"Max distance reachable in 60 ticks at 30 Hz: {max_dist_30hz:.1f} dm ({max_dist_30hz/10:.2f} m)")
        print(f"Max distance reachable in 60 ticks at 10 Hz: {max_dist_10hz:.1f} dm ({max_dist_10hz/10:.2f} m)")

        random.seed(42)
        TRIALS = 10000

        print("\nMonte Carlo Expiry Rate (10,000 random source-destination pairs per biome):")
        for name, side in biomes.items():
            expired_30hz = 0
            expired_10hz = 0
            for _ in range(TRIALS):
                x1, y1 = random.uniform(0, side), random.uniform(0, side)
                x2, y2 = random.uniform(0, side), random.uniform(0, side)
                dist = math.hypot(x2 - x1, y2 - y1)
                if dist > max_dist_30hz:
                    expired_30hz += 1
                if dist > max_dist_10hz:
                    expired_10hz += 1

            pct_30hz = (expired_30hz / TRIALS) * 100.0
            pct_10hz = (expired_10hz / TRIALS) * 100.0
            print(f"  * {name:<30}: 30 Hz Expiry = {pct_30hz:5.1f}% | 10 Hz Expiry = {pct_10hz:5.1f}%")

            # At 30 Hz, all biomes have over 65% premature lease expiry!
            self.assertGreater(pct_30hz, 65.0)

        print("\nCONFIRMED BUG:")
        print("A hardcoded 60-tick TTL lease without distance-adaptive scaling guarantees that the vast majority (>65% to >90%)")
        print("of affordance reservations expire while the agent is still walking towards them, creating severe resource race conditions.")

