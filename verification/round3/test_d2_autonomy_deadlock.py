@dataclass
class Affordance:
    name: str
    x: float # decimeters
    priority: float
    fatigue_cost_rate: float # fatigue generated by doing or walking to this task
    is_rest: bool = False

class NavigationAgent:
    """
    Implements Backlog Story 2.2 utility function:
    U(Task) = Priority + Alignment + Focus - StressCost - Fatigue.
    Evaluates dynamic whim switching during transit.
    """
    def __init__(self, x: float = 60.0):
        self.x = x # position in decimeters (0..120)
        self.speed = 0.4 # dm per tick
        self.fatigue = 0.10 # 0.0 .. 1.0
        self.focus = 0.80
        self.current_goal: Optional[Affordance] = None
        self.in_action_phase: bool = False
        self.switches: int = 0
        self.completed_tasks = 0

    def evaluate_task_utility(self, affordance: Affordance) -> float:
        # Distance penalty (time to reach) adds fatigue anticipation
        dist = abs(self.x - affordance.x)
        if affordance.is_rest:
            # Rest becomes much more desirable as fatigue rises
            return affordance.priority + self.fatigue * 0.8 - (dist / 200.0)
        else:
            # Heavy task utility plummets as fatigue rises
            return affordance.priority + self.focus * 0.2 - self.fatigue * 0.8 - (dist / 200.0)

    def step_tick(self, task_work: Affordance, task_rest: Affordance):
        u_work = self.evaluate_task_utility(task_work)
        u_rest = self.evaluate_task_utility(task_rest)

        HYSTERESIS = 0.25 # 25% utility threshold from GDD 3.4

        # Action phase check
        if self.current_goal is not None:
            dist = abs(self.x - self.current_goal.x)
            if dist < 2.0:
                self.in_action_phase = True
                if self.current_goal.is_rest:
                    self.fatigue = max(0.0, self.fatigue - 0.01) # resting recovers fatigue
                else:
                    self.fatigue = min(1.0, self.fatigue + 0.005) # working adds fatigue
                return

        self.in_action_phase = False

        # Transit adds physical walking fatigue
        self.fatigue = min(1.0, self.fatigue + 0.002)

        # Hysteresis decision loop during navigation
        if self.current_goal is None:
            self.current_goal = task_work if u_work >= u_rest else task_rest
            self.switches += 1
        elif self.current_goal == task_work:
            if u_rest > u_work + HYSTERESIS:
                self.current_goal = task_rest
                self.switches += 1
        elif self.current_goal == task_rest:
            if u_work > u_rest + HYSTERESIS:
                self.current_goal = task_work
                self.switches += 1

        # Move towards goal
        if self.current_goal is not None:
            if self.x < self.current_goal.x:
                self.x += self.speed
            else:
                self.x -= self.speed

class TestD2NavigationHysteresis(unittest.TestCase):
    def test_navigation_thrashing_and_hysteresis_effectiveness(self):
        print("\n--- [TEST D2.1] Comparative Whim Oscillation & Hysteresis Evaluation ---")
        
        # Test Case A: Without Hysteresis (0% threshold) under fluctuating whim utilities
        class WhimAgent:
            def __init__(self, hysteresis: float):
                self.x = 60.0
                self.speed = 0.4
                self.hysteresis = hysteresis
                self.current_goal: Optional[int] = None # 0 or 1
                self.switches = 0
                self.completed = 0

            def step(self, t: int):
                # Two whims with oscillating urge (e.g. fluctuating social need vs thirst)
                u0 = 0.70 + 0.15 * math.sin(t * 0.05)
                u1 = 0.70 + 0.15 * math.cos(t * 0.05)

                if self.current_goal is None:
                    self.current_goal = 0 if u0 >= u1 else 1
                    self.switches += 1
                elif self.current_goal == 0:
                    if u1 > u0 + self.hysteresis:
                        self.current_goal = 1
                        self.switches += 1
                elif self.current_goal == 1:
                    if u0 > u1 + self.hysteresis:
                        self.current_goal = 0
                        self.switches += 1

                # Goal 0 is at x = 10, Goal 1 is at x = 110
                target_x = 10.0 if self.current_goal == 0 else 110.0
                if abs(self.x - target_x) < 2.0:
                    self.completed += 1
                    # reset
                    self.x = 60.0
                    self.current_goal = None
                else:
                    self.x += self.speed if self.x < target_x else -self.speed

        # Run without hysteresis
        agent_no_hyst = WhimAgent(hysteresis=0.0)
        for t in range(1200):
            agent_no_hyst.step(t)

        # Run with 25% hysteresis
        agent_hyst = WhimAgent(hysteresis=0.25)
        for t in range(1200):
            agent_hyst.step(t)

        print(f"Without Hysteresis (0%): Switches = {agent_no_hyst.switches}, Tasks Completed = {agent_no_hyst.completed}")
        print(f"With 25% Hysteresis: Switches = {agent_hyst.switches}, Tasks Completed = {agent_hyst.completed}")

        # Without hysteresis, agent thrashes wildly and completes 0 tasks
        self.assertGreater(agent_no_hyst.switches, 15)
        self.assertEqual(agent_no_hyst.completed, 0)

        # With 25% hysteresis, agent suppresses small oscillations and completes tasks
        self.assertLess(agent_hyst.switches, agent_no_hyst.switches)
        self.assertGreater(agent_hyst.completed, 0)
        print("PASS: 25% utility hysteresis successfully dampens high-frequency whim oscillation,")
        print("allowing task completion compared to unmitigated thrashing.")


