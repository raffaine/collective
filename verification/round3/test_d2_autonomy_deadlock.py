class AffordanceFsmAgent:
    """Simulates 30-tick watchdog timer and 120-tick destination blacklist from GDD 3.4."""
    def __init__(self):
        self.x = 0.0 # position dm
        self.current_task: Optional[str] = None
        self.ticks_in_task = 0
        self.watchdog_counter = 0
        self.blacklist: Dict[str, int] = {} # task_name -> ticks_remaining
        self.last_distance = 1000.0
        self.task_history: List[str] = []
        self.abort_count = 0

    def step_tick(self, blocked_affordance_dist: float = 50.0):
        # 1. Update blacklist timers
        expired = []
        for task, remaining in self.blacklist.items():
            if remaining <= 1:
                expired.append(task)
            else:
                self.blacklist[task] = remaining - 1
        for task in expired:
            del self.blacklist[task]

        # 2. Evaluate utilities
        # Task A: Critical Water Well (Unreachable / Blocked path). Utility = 0.95
        # Task B: Turn Compost (Reachable, low utility). Utility = 0.40
        u_well = 0.95
        u_compost = 0.40
        HYSTERESIS = 0.25 # 25%

        # Select candidate
        candidate = None
        if "WELL" not in self.blacklist:
            candidate = "WELL"
        else:
            candidate = "COMPOST"

        # Apply hysteresis if currently working on a task
        if self.current_task is None:
            self.current_task = candidate
            self.ticks_in_task = 0
            self.watchdog_counter = 0
            self.last_distance = blocked_affordance_dist if candidate == "WELL" else 10.0
        elif self.current_task == "COMPOST" and candidate == "WELL":
            # Can switch if u_well > u_compost + 0.25 (0.95 > 0.40 + 0.25 = 0.65) -> YES!
            if u_well > u_compost + HYSTERESIS:
                self.current_task = "WELL"
                self.ticks_in_task = 0
                self.watchdog_counter = 0
                self.last_distance = blocked_affordance_dist

        self.task_history.append(self.current_task)

        # 3. Simulate execution & 30-Tick Progress Watchdog
        if self.current_task == "WELL":
            # Well is physically blocked by debris; distance NEVER decreases
            current_dist = blocked_affordance_dist # constant distance
            if current_dist >= self.last_distance:
                self.watchdog_counter += 1
            else:
                self.watchdog_counter = 0

            self.last_distance = current_dist

            # GDD 3.4 line 302:
            # "If an agent's physical distance to an objective fails to decrease over 30 consecutive ticks,
            # the task transitions to ACTION_BLOCKED. The agent steps back 1 decimeter, releases reservations,
            # blacklists the destination for 120 ticks, and re-evaluates utility."
            if self.watchdog_counter >= 30:
                self.abort_count += 1
                self.blacklist["WELL"] = 120 # Blacklist for 120 ticks
                self.current_task = None
                self.watchdog_counter = 0
        elif self.current_task == "COMPOST":
            # Compost task makes continuous progress
            self.ticks_in_task += 1

class TestD2WatchdogLivelock(unittest.TestCase):
    def test_unfulfillable_affordance_periodic_livelock(self):
        print("\n--- [TEST D2.2] Unfulfillable Affordance Watchdog Livelock Simulation ---")
        agent = AffordanceFsmAgent()

        # Run 600 ticks (20 seconds of game simulation at 30 Hz)
        for t in range(600):
            agent.step_tick(blocked_affordance_dist=50.0)

        # Count how many times the agent bounced back into the blocked well
        print(f"Simulation 600 ticks complete. Watchdog ACTION_BLOCKED triggers: {agent.abort_count}")
        
        # Analyze periodic cycle:
        # 30 ticks trying WELL -> 120 ticks doing COMPOST -> 30 ticks trying WELL -> 120 ticks COMPOST...
        # Period = 150 ticks. In 600 ticks, exactly 4 abort cycles should occur.
        self.assertEqual(agent.abort_count, 4)

        # Compute fraction of time spent futilely attempting blocked well
        well_ticks = agent.task_history.count("WELL")
        compost_ticks = agent.task_history.count("COMPOST")
        well_ratio = well_ticks / len(agent.task_history)
        print(f"Time spent in blocked WELL: {well_ticks} ticks ({well_ratio*100:.1f}%)")
        print(f"Time spent in COMPOST: {compost_ticks} ticks")

        self.assertGreater(well_ratio, 0.15, "Agent spent substantial recurring time trapped in blocked affordance livelock")
        print("CONFIRMED BUG:")
        print("The 120-tick blacklist has NO persistent failure counter or exponential backoff.")
        print("Every time the 120 ticks expire, high-utility unfulfillable affordances immediately preempt productive work,")
        print("causing a permanent 150-tick periodic livelock cycle.")


